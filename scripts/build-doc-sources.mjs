// Generates `src/content/docs/doc-sources.ts` from the MDX files on disk.
//
// The docs page needs the raw markdown for two things a compile step cannot give
// us: the table of contents (real heading ids) and the search index. A generated
// module is used instead of `import.meta.glob("?raw")` because test runners do not
// all honour the `?raw` query, and a silent empty index is worse than a build step.
//
// Usage:
//   node scripts/build-doc-sources.mjs           write the file
//   node scripts/build-doc-sources.mjs --check    fail if it is out of date

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DOCS_DIR = "src/content/docs";
const OUT = join(DOCS_DIR, "doc-sources.ts");
const check = process.argv.includes("--check");

const slugs = readdirSync(DOCS_DIR)
  .filter((name) => name.endsWith(".mdx"))
  .map((name) => name.replace(/\.mdx$/, ""))
  .sort();

const body = slugs
  .map((slug) => {
    const text = readFileSync(join(DOCS_DIR, `${slug}.mdx`), "utf8");
    return `  ${JSON.stringify(slug)}: ${JSON.stringify(text)},`;
  })
  .join("\n");

const file = `// Generated by scripts/build-doc-sources.mjs — do not edit by hand.
// Run \`npm run docs:index\` after changing any page in ${DOCS_DIR}.

/** The raw markdown of every docs page, keyed by slug. */
export const DOC_SOURCES: Record<string, string> = {
${body}
};
`;

if (check) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    current = "";
  }
  if (current !== file) {
    console.error(`${OUT} is out of date. Run: npm run docs:index`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${slugs.length} pages).`);
} else {
  writeFileSync(OUT, file);
  console.log(`Wrote ${OUT} (${slugs.length} pages).`);
}
